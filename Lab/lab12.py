### Phase 1: The Player Class
class Player:
    """
    >>> random = make_test_random()
    >>> p1 = Player('Hill', random)
    >>> p2 = Player('Don', random)
    >>> p1.popularity
    100
    >>> p1.debate(p2)  # random() should return 0.0
    >>> p1.popularity
    150
    >>> p2.popularity
    100
    >>> p2.votes
    0
    >>> p2.speech(p1)
    >>> p2.votes
    10
    >>> p2.popularity
    110
    >>> p1.popularity
    135
    >>> p1.speech(p2)
    >>> p1.votes
    13
    >>> p1.popularity
    148
    >>> p2.votes
    10
    >>> p2.popularity
    99
    >>> for _ in range(4):  # 0.1, 0.2, 0.3, 0.4
    ...     p1.debate(p2)
    >>> p2.debate(p1)
    >>> p2.popularity
    49
    >>> p2.debate(p1)
    >>> p2.popularity
    0
    """
    def __init__(self, name, random_func):
        self.name = name
        self.votes = 0
        self.popularity = 100
        self.random_func = random_func

    def debate(self, other):
        p1, p2 = self.popularity, other.popularity
        probability = max(0.1, p1/(p1+p2))
        if self.random_func() < probability:
            self.popularity += 50
        else:
            self.popularity -= 50
            if self.popularity <0:
                self.popularity = 0

    def speech(self, other):
        p1, p2 = self.popularity, other.popularity
        self.popularity += (p1 // 10)
        self.votes += (p1 // 10)
        other.popularity -= (p2 // 10)

    def choose(self, other):
        return self.speech


### Phase 2: The Game Class
class Game:
    """
    >>> random = make_test_random()
    >>> p1, p2 = Player('Hill',random), Player('Don', random)
    >>> g = Game(p1, p2)
    >>> winner = g.play()
    >>> p1 is winner
    True
    >>> # Additional correctness tests
    >>> winner is g.winner()
    True
    >>> g.turn
    10
    >>> p1.votes = p2.votes
    >>> print(g.winner())
    None
    """
    def __init__(self, player1, player2):
        self.p1 = player1
        self.p2 = player2
        self.turn = 0

    def play(self):
        while not self.game_over():
            self.p1.choose(self.p2)(self.p2)
            self.turn += 1
            if self.game_over():
                break
            self.p2.choose(self.p1)(self.p1)
            self.turn += 1
        return self.winner()

    def game_over(self):
        return max(self.p1.votes, self.p2.votes) >= 50 or self.turn >= 10

    def winner(self): # 通过测试样例可以看出返回值为Player实例
        if self.turn >= 10:
            if self.p1.votes == self.p2.votes:
                return None
            elif self.p1.votes > self.p2.votes:
                return self.p1
            else:
                return self.p2
        elif self.p1.votes >= 50 and self.p2.votes < 50:
            return self.p1
        elif self.p1.votes < 50 and self.p2.votes >= 50:
            return self.p2


